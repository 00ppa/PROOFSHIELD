"""Alert schemas."""

from datetime import datetime
from typing import Any, Dict, Literal, Optional
from pydantic import Field, field_validator
from proofshield.schemas.common import ProofshieldBaseModel, validate_nesting_depth


class AlertV1(ProofshieldBaseModel):
    """Security alert record (Schema Version 1).

    Represents an alert generated by a security monitoring system when
    a detection rule matches observed telemetry.
    """

    schema_version: Literal["v1"] = "v1"
    alert_id: str = Field(
        ...,
        min_length=3,
        description="Unique alert identifier in PROOFSHIELD",
    )
    source_alert_id: str = Field(
        ...,
        min_length=1,
        description="Original alert identifier from the source monitoring system",
    )
    source_type: str = Field(
        ...,
        min_length=1,
        description="Source monitoring system (e.g. wazuh, splunk, sentinel)",
    )
    alert_timestamp: Optional[datetime] = Field(
        None,
        description="Timestamp (UTC) when the alert was generated by the detection rule",
    )
    ingested_at: Optional[datetime] = Field(
        None,
        description="Timestamp (UTC) when PROOFSHIELD ingested the alert record",
    )
    host_id: str = Field(
        ...,
        min_length=1,
        description="Host identifier associated with the alert",
    )
    rule_reference: Optional[str] = Field(
        None,
        description="Detection rule ID that triggered this alert",
    )
    alert_title: Optional[str] = Field(
        None,
        description="Human-readable alert title",
    )
    severity: Optional[str] = Field(
        None,
        description="Alert severity level (e.g. low, medium, high, critical)",
    )
    raw_record_reference: Optional[str] = Field(
        None,
        description="Reference to the original raw alert record",
    )
    execution_token: Optional[str] = Field(
        None,
        description="Optional execution token for causal attribution",
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Additional alert metadata and context",
    )

    @field_validator("metadata")
    @classmethod
    def validate_metadata_depth(cls, v: Dict[str, Any]) -> Dict[str, Any]:
        if v:
            validate_nesting_depth(v, max_depth=32)
        return v
